const LangContext = createContext({ lang: 'zh', setLang: () => {}, t: (k, fallback) => fallback || k });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('appLang') || 'zh');
  const setLang = useCallback((l) => { localStorage.setItem('appLang', l); setLangState(l); document.documentElement.lang = l; }, []);
  const t = useCallback((key, fallback) => { const entry = DICT[key]; if (!entry) return fallback || key; return entry[lang] || entry.zh || fallback || key; }, [lang]);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

